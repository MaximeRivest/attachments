/**
 * Write `src/generated/` from the contract: `node tools/generate.ts`.
 *
 * - `schema.ts`: `contract/dsl-schema.json` (every option of every format
 *   and source), each distinct option stored once.
 * - `options.ts`: the `Options` type `att()` takes, one property per
 *   option under its contract name, with its help as documentation.
 *
 * `tests/generated.test.ts` fails when these differ from the contract.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");

interface Decl {
  name: string;
  type: string;
  aliases: string[];
  param: string | null;
  default: unknown;
  help: string;
  example: string;
}

interface Schema {
  version: number;
  processors: Record<string, Decl[]>;
  sources: Record<string, Decl[]>;
}

export function readSchema(): Schema {
  return JSON.parse(readFileSync(join(root, "..", "contract", "dsl-schema.json"), "utf8")) as Schema;
}

export function schemaModule(schema: Schema): string {
  const table: Decl[] = [];
  const index = new Map<string, number>();
  const ref = (d: Decl): number => {
    const key = JSON.stringify(d);
    let i = index.get(key);
    if (i === undefined) {
      i = table.length;
      table.push(d);
      index.set(key, i);
    }
    return i;
  };
  const group = (g: Record<string, Decl[]>): Record<string, number[]> =>
    Object.fromEntries(Object.entries(g).map(([k, list]) => [k, list.map(ref)]));
  const processors = group(schema.processors);
  const sources = group(schema.sources);
  return `// GENERATED by tools/generate.ts from contract/dsl-schema.json — do not edit.
import type { OptionDecl } from "../options.ts";

/** Every distinct option declaration. */
const DECLS: readonly OptionDecl[] = ${JSON.stringify(table, null, 1)};

const pick = (ids: readonly number[]): readonly OptionDecl[] => ids.map((i) => DECLS[i]!);

/** Options of each processor key (\`.pdf\`, \`__text__\`). */
export const PROCESSOR_OPTIONS: Readonly<Record<string, readonly OptionDecl[]>> = Object.fromEntries(
  Object.entries(${JSON.stringify(processors)} as Record<string, number[]>).map(([k, ids]) => [k, pick(ids)]),
);

/** Options of each source prefix (\`file://\`, \`github://\`). */
export const SOURCE_OPTIONS: Readonly<Record<string, readonly OptionDecl[]>> = Object.fromEntries(
  Object.entries(${JSON.stringify(sources)} as Record<string, number[]>).map(([k, ids]) => [k, pick(ids)]),
);

export const SCHEMA_VERSION = ${schema.version};
`;
}

const TS_TYPES: Record<string, string> = {
  str: "string",
  int: "number",
  float: "number",
  bool: "boolean",
  pages: "number | string | readonly [first: number, last: number]",
  bool_or_auto: 'boolean | "auto" | "always"',
  str_or_int: "string | number",
};

export function optionsModule(schema: Schema): string {
  const byName = new Map<string, { types: Set<string>; decl: Decl; keys: string[] }>();
  for (const [key, list] of [...Object.entries(schema.processors), ...Object.entries(schema.sources)]) {
    for (const d of list) {
      const entry = byName.get(d.name) ?? { types: new Set<string>(), decl: d, keys: [] };
      entry.types.add(d.type);
      entry.keys.push(key);
      byName.set(d.name, entry);
    }
  }
  const lines: string[] = [];
  for (const name of [...byName.keys()].sort()) {
    const { types, decl, keys } = byName.get(name)!;
    const type = [...new Set([...types].flatMap((t) => TS_TYPES[t]!.split(" | ")))].join(" | ");
    const where = keys.filter((k) => k !== "__text__").map((k) => (k.includes("://") ? k : k));
    const doc = [decl.help.replace(/\*\//g, "*\\/")];
    if (decl.example) doc.push("", `@example \`[${decl.example}]\``);
    if (decl.default !== null && decl.default !== undefined) doc.push(`@defaultValue \`${JSON.stringify(decl.default)}\``);
    doc.push("", `Read by: ${where.length > 12 ? `${where.slice(0, 12).join(", ")} and ${where.length - 12} more` : where.join(", ") || "text files"}.`);
    lines.push(`  /**\n${doc.map((l) => (l ? `   * ${l}` : "   *")).join("\n")}\n   */\n  ${name}?: ${type};`);
  }
  return `// GENERATED by tools/generate.ts from contract/dsl-schema.json — do not edit.

/**
 * Options \`att()\` takes, by their contract names: the same names as in
 * \`"report.pdf[pages: 1-4]"\`, in warnings, in \`att.options()\` and on the
 * server. Aliases (\`pw\`, \`slides\`, …) work in the string only.
 */
export interface Options {
${lines.join("\n")}
  /** Which processor reads the file, when named processors are registered (\`processor({ name })\`). */
  processor?: string;
}
`;
}

export function readReadingData(): unknown {
  return JSON.parse(readFileSync(join(root, "..", "contract", "reading-data.json"), "utf8"));
}

export function readingModule(data: unknown): string {
  return `// GENERATED by tools/generate.ts from contract/reading-data.json — do not edit.

/** Tables every implementation copies (contract/reading.md). */
export const READING = ${JSON.stringify(data, null, 1)} as const;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const schema = readSchema();
  writeFileSync(join(root, "src", "generated", "schema.ts"), schemaModule(schema));
  writeFileSync(join(root, "src", "generated", "options.ts"), optionsModule(schema));
  writeFileSync(join(root, "src", "generated", "reading.ts"), readingModule(readReadingData()));
  console.log("wrote src/generated/schema.ts, options.ts and reading.ts");
}
